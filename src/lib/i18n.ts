export type AppLanguage = 'en' | 'sw';

export function getInitialLanguage(): AppLanguage {
  try {
    const saved = window.localStorage.getItem('netco_lang');
    if (saved === 'sw' || saved === 'en') return saved;
  } catch {
    // ignore storage errors
  }
  return 'en';
}

export function saveLanguage(lang: AppLanguage) {
  try {
    window.localStorage.setItem('netco_lang', lang);
  } catch {
    // ignore storage errors
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang;
  }
}

export function formatDurationLocalized(minutes: number, lang: AppLanguage): string {
  if (lang === 'en') {
    if (minutes < 60) return `${minutes} min`;
    if (minutes < 1440) {
      const hrs = Math.round((minutes / 60) * 10) / 10;
      return `${hrs} hr${hrs === 1 ? '' : 's'}`;
    }
    const days = Math.round((minutes / 1440) * 10) / 10;
    return `${days} day${days === 1 ? '' : 's'}`;
  }

  if (minutes < 60) return `Dakika ${minutes}`;
  if (minutes < 1440) {
    const hrs = Math.round((minutes / 60) * 10) / 10;
    return hrs === 1 ? 'Saa 1' : `Masaa ${hrs}`;
  }
  const days = Math.round((minutes / 1440) * 10) / 10;
  return `Siku ${days}`;
}

